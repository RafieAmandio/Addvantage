/** UTC date `n` business days before today (Sat and Sun skipped). */
function businessDaysAgo(n: number): Date {
  const d = new Date();
  d.setUTCHours(0, 30, 0, 0); // 07:30 WIB
  while (n > 0) {
    d.setUTCDate(d.getUTCDate() - 1);
    if (d.getUTCDay() !== 0 && d.getUTCDay() !== 6) n--;
  }
  return d;
}

/** Plans with dates relative to now, newest first. `at` is the publish time. Fresh on every call. */
export function tradingPlans(): (TradingPlan & { at: string })[] {
  return seeds.map(({ d, ...p }) => {
    // Today's plan went out about 90 minutes ago, older ones at 07:30 WIB.
    const at = d === 0 ? new Date(Date.now() - 95 * 60_000) : businessDaysAgo(d);
    return { ...p, date: at.toISOString().slice(0, 10), at: at.toISOString() };
  });
}
